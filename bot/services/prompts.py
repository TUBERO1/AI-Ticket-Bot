def _format_won(amount: int) -> str:
    if amount >= 10000:
        man = amount / 10000
        if man == int(man):
            return f"{int(man)}만원"
        return f"{man:.1f}만원".replace(".0만", "만")
    return f"{amount:,}원"


def is_price_question(text: str) -> bool:
    lowered = text.lower()
    return any(re.search(p, lowered) for p in PRICE_TRIGGERS)


def is_timeline_question(text: str) -> bool:
    lowered = text.lower()
    return any(re.search(p, lowered) for p in TIMELINE_TRIGGERS)


def _detect_service(text: str) -> str | None:
    lowered = text.lower()
    for pattern, key in SERVICE_HINTS:
        if re.search(pattern, lowered, re.I):
            return key
    return None


